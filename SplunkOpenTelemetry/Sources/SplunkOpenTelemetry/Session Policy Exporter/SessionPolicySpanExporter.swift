internal import CiscoLogger
import Foundation
import OpenTelemetryApi
import OpenTelemetrySdk
import SplunkCommon

/// Drops spans whose `session.id` does not have the shape of an ID the agent generates.
///
/// The stage runs before the customer span interceptor, so the interceptor never sees a span that
/// cannot be exported. `SpanInterceptorExporter` then drops any span whose ID the interceptor changed.
///
/// This stage is stateless on purpose. It owns no lifecycle policy, no retained telemetry and no
/// history.
final class SessionPolicySpanExporter: SpanExporter {

    // MARK: - Constants

    static let sessionIdKey = SessionAttributeKeys.sessionId


    // MARK: - Private

    private let proxyExporter: SpanExporter

    /// Receives the number of spans dropped from one batch, or is `nil` when debug logging is off.
    private let droppedCountLog: ((Int) -> Void)?


    // MARK: - Initialization

    /// Creates the stage in front of `proxy`.
    ///
    /// - Parameters:
    ///   - proxy: The exporter that receives the spans this stage keeps.
    ///   - debugEnabled: Whether to log how many spans each batch dropped.
    ///   - logDroppedCount: Writes that log line instead of the internal logger. Used by tests.
    init(proxy: SpanExporter, debugEnabled: Bool = false, logDroppedCount: ((Int) -> Void)? = nil) {
        proxyExporter = proxy

        if debugEnabled {
            droppedCountLog = logDroppedCount ?? Self.makeDroppedCountLog()
        }
        else {
            droppedCountLog = nil
        }
    }


    // MARK: - SpanExporter

    func export(spans: [SpanData], explicitTimeout: TimeInterval?) -> SpanExporterResultCode {
        let eligibleSpans = spans.filter(Self.carriesRealSessionID)

        // One line per batch, computed from the two counts only.
        if let droppedCountLog, eligibleSpans.count < spans.count {
            droppedCountLog(spans.count - eligibleSpans.count)
        }

        guard !eligibleSpans.isEmpty else {
            // An intentional terminal decision. Reporting success prevents retry and disk growth for
            // telemetry that cannot belong to a session.
            return .success
        }

        return proxyExporter.export(spans: eligibleSpans, explicitTimeout: explicitTimeout)
    }

    func flush(explicitTimeout: TimeInterval?) -> SpanExporterResultCode {
        proxyExporter.flush(explicitTimeout: explicitTimeout)
    }

    func shutdown(explicitTimeout: TimeInterval?) {
        proxyExporter.shutdown(explicitTimeout: explicitTimeout)
    }


    // MARK: - Debug logging

    private static func makeDroppedCountLog() -> (Int) -> Void {
        let logger = DefaultLogAgent(poolName: PackageIdentifier.instance(), category: "OpenTelemetry")

        return { droppedCount in
            logger.log(level: .debug) {
                "Session policy dropped \(droppedCount) span(s) without a session ID generated by the agent."
            }
        }
    }


    // MARK: - Eligibility

    private static func carriesRealSessionID(_ span: SpanData) -> Bool {
        guard case let .string(sessionID)? = span.attributes[sessionIdKey] else {
            return false
        }

        return isGeneratedSessionID(sessionID)
    }

    /// Whether the value has the shape of an ID this SDK generates: 32 lowercase hexadecimal digits.
    ///
    /// Checking the shape rather than mere presence rejects an empty string, a placeholder such as
    /// `"undefined"`, a sentinel UUID, and a corrupted persisted value. The shape is defined in
    /// `SessionAttributeKeys`. Deliberately byte-wise and allocation-free, because this runs for every
    /// exported span.
    private static func isGeneratedSessionID(_ value: String) -> Bool {
        let digits = value.utf8

        guard digits.count == SessionAttributeKeys.agentSessionIdLength else {
            return false
        }

        return digits.allSatisfy(SessionAttributeKeys.isAgentSessionIdDigit)
    }
}
